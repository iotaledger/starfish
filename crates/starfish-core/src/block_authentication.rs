/// Generates every enum that must dispatch over the concrete post-quantum
/// schemes. `tag` is the byte prefix used in the binary encoding of
/// [`BlockAuthentication`]; tags are append-only (0 = none, 1 = Ed25519).
macro_rules! block_authentication_schemes {
    ($( $variant:ident($scheme:ty, $name:literal) = $tag:literal ),+ $(,)?) => {
        /// Signature scheme selected for block headers (node parameter
        /// `block_authentication`, CLI `--block-authentication`).
        #[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash, Serialize, Deserialize)]
        pub enum BlockAuthenticationScheme {
            #[default]
            #[serde(rename = "ed25519")]
            Ed25519,
            $(
                #[serde(rename = $name)]
                $variant,
            )+
        }

        impl BlockAuthenticationScheme {
            pub const ALL: &'static [Self] = &[Self::Ed25519, $( Self::$variant, )+];

            pub fn name(self) -> &'static str {
                match self {
                    Self::Ed25519 => "ed25519",
                    $( Self::$variant => <$scheme>::NAME, )+
                }
            }

            pub fn is_post_quantum(self) -> bool {
                !matches!(self, Self::Ed25519)
            }

            pub fn public_key_size(self) -> usize {
                match self {
                    Self::Ed25519 => 32,
                    $( Self::$variant => <$scheme>::PUBLIC_KEY_SIZE, )+
                }
            }

            pub fn signature_size(self) -> usize {
                match self {
                    Self::Ed25519 => crate::crypto::SIGNATURE_SIZE,
                    $( Self::$variant => <$scheme>::SIGNATURE_SIZE, )+
                }
            }

            fn wire_tag(self) -> u8 {
                match self {
                    Self::Ed25519 => 1,
                    $( Self::$variant => $tag, )+
                }
            }

            fn from_wire_tag(tag: u8) -> Option<Self> {
                match tag {
                    1 => Some(Self::Ed25519),
                    $( $tag => Some(Self::$variant), )+
                    _ => None,
                }
            }
        }

        /// Authentication proof over the block content digest, carried in the
        /// header but excluded from the block reference.
        #[derive(Clone, PartialEq, Eq)]
        pub enum BlockAuthentication {
            /// Only valid for locally constructed genesis blocks.
            None,
            Ed25519(SignatureBytes),
            $( $variant(PqSignature<$scheme>), )+
        }

        impl BlockAuthentication {
            pub fn scheme(&self) -> Option<BlockAuthenticationScheme> {
                match self {
                    Self::None => None,
                    Self::Ed25519(_) => Some(BlockAuthenticationScheme::Ed25519),
                    $( Self::$variant(_) => Some(BlockAuthenticationScheme::$variant), )+
                }
            }

            fn payload(&self) -> &[u8] {
                match self {
                    Self::None => &[],
                    Self::Ed25519(signature) => signature.as_bytes(),
                    $( Self::$variant(signature) => signature.as_bytes(), )+
                }
            }

            fn from_parts(scheme: BlockAuthenticationScheme, bytes: &[u8]) -> Result<Self, String> {
                match scheme {
                    BlockAuthenticationScheme::Ed25519 => {
                        SignatureBytes::try_from(bytes).map(Self::Ed25519)
                    }
                    $(
                        BlockAuthenticationScheme::$variant => {
                            PqSignature::<$scheme>::from_bytes(bytes).map(Self::$variant)
                        }
                    )+
                }
            }
        }

        /// Post-quantum public key of one committee member.
        #[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
        pub enum BlockPublicKey {
            $(
                #[serde(rename = $name)]
                $variant(PqPublicKey<$scheme>),
            )+
        }

        impl BlockPublicKey {
            pub fn scheme(&self) -> BlockAuthenticationScheme {
                match self {
                    $( Self::$variant(_) => BlockAuthenticationScheme::$variant, )+
                }
            }

            /// `true` iff `authentication` is a valid proof of the same scheme
            /// over `digest` under this key.
            pub fn verify(
                &self,
                digest: &BlockDigest,
                authentication: &BlockAuthentication,
            ) -> bool {
                match (self, authentication) {
                    $(
                        (Self::$variant(key), BlockAuthentication::$variant(signature)) => {
                            key.verify(digest.as_array(), signature)
                        }
                    )+
                    _ => false,
                }
            }
        }

        /// Post-quantum private key of one validator.
        #[derive(Clone, Debug, Serialize, Deserialize)]
        pub enum BlockSigningKey {
            $(
                #[serde(rename = $name)]
                $variant(PqSigner<$scheme>),
            )+
        }

        impl BlockSigningKey {
            /// Deterministically derive a key for `scheme`. Returns `None` for
            /// Ed25519, which uses the validator's identity key instead.
            pub fn from_seed(scheme: BlockAuthenticationScheme, seed: &[u8; 32]) -> Option<Self> {
                match scheme {
                    BlockAuthenticationScheme::Ed25519 => None,
                    $(
                        BlockAuthenticationScheme::$variant => {
                            Some(Self::$variant(PqSigner::<$scheme>::from_seed(seed)))
                        }
                    )+
                }
            }

            pub fn scheme(&self) -> BlockAuthenticationScheme {
                match self {
                    $( Self::$variant(_) => BlockAuthenticationScheme::$variant, )+
                }
            }

            pub fn public_key(&self) -> BlockPublicKey {
                match self {
                    $( Self::$variant(key) => BlockPublicKey::$variant(key.public_key()), )+
                }
            }

            pub fn sign(&self, digest: &BlockDigest) -> BlockAuthentication {
                match self {
                    $(
                        Self::$variant(key) => {
                            BlockAuthentication::$variant(key.sign(digest.as_array()))
                        }
                    )+
                }
            }
        }
    };
}

