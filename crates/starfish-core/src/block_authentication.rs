// ---------------------------------------------------------------------------
// SLH-DSA (FIPS 205) — RustCrypto `slh-dsa`
// ---------------------------------------------------------------------------

macro_rules! impl_slh_dsa_scheme {
    ($marker:ident, $params:ty, $name:literal, n = $n:literal, sig = $sig:literal) => {
        #[derive(Clone, Copy, Debug, PartialEq, Eq)]
        pub struct $marker;

        impl PqSignatureScheme for $marker {
            const NAME: &'static str = $name;
            /// pk = PK.seed || PK.root
            const PUBLIC_KEY_SIZE: usize = 2 * $n;
            /// sk = SK.seed || SK.prf || PK.seed || PK.root
            const SECRET_KEY_SIZE: usize = 4 * $n;
            const SIGNATURE_SIZE: usize = $sig;

            type SigningKey = slh_dsa::SigningKey<$params>;
            type VerifyingKey = slh_dsa::VerifyingKey<$params>;

            fn keygen_from_seed(seed: &[u8; 32]) -> Self::SigningKey {
                // FIPS 205 Algorithm 21: keygen from (SK.seed, SK.prf, PK.seed).
                let mut material = [0u8; 3 * $n];
                expand_seed($name, seed, &mut material);
                let (sk_seed, rest) = material.split_at($n);
                let (sk_prf, pk_seed) = rest.split_at($n);
                slh_dsa::SigningKey::<$params>::slh_keygen_internal(sk_seed, sk_prf, pk_seed)
            }

            fn signing_key_to_bytes(key: &Self::SigningKey) -> Vec<u8> {
                key.to_vec()
            }

            fn signing_key_from_bytes(bytes: &[u8]) -> Option<Self::SigningKey> {
                slh_dsa::SigningKey::<$params>::try_from(bytes).ok()
            }

            fn verifying_key(key: &Self::SigningKey) -> Self::VerifyingKey {
                slh_dsa::signature::Keypair::verifying_key(key)
            }

            fn verifying_key_to_bytes(key: &Self::VerifyingKey) -> Vec<u8> {
                key.to_vec()
            }

            fn verifying_key_from_bytes(bytes: &[u8]) -> Option<Self::VerifyingKey> {
                slh_dsa::VerifyingKey::<$params>::try_from(bytes).ok()
            }

            fn sign(key: &Self::SigningKey, message: &[u8]) -> Vec<u8> {
                // `try_sign` is the deterministic variant (opt_rand = PK.seed).
                let signature: slh_dsa::Signature<$params> =
                    slh_dsa::signature::Signer::try_sign(key, message)
                        .expect("SLH-DSA signing is infallible for a valid key");
                signature.to_vec()
            }

            fn verify(key: &Self::VerifyingKey, message: &[u8], signature: &[u8]) -> bool {
                let Ok(signature) = slh_dsa::Signature::<$params>::try_from(signature) else {
                    return false;
                };
                slh_dsa::signature::Verifier::verify(key, message, &signature).is_ok()
            }
        }
    };
}

