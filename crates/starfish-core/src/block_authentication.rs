//! Pluggable block-header authentication.
//!
//! A block reference is the BLAKE3 digest of the header *content*; the
//! authentication proof is a separate header field that never enters the
//! digest. This makes the block identity independent of the signature scheme,
//! so every consensus protocol can be run unchanged with any scheme listed in
//! [`BlockAuthenticationScheme`].
//!
//! Ed25519 (the default) keeps using the committee's identity key. Post-quantum
//! schemes are implemented behind [`PqSignatureScheme`]; each scheme is a
//! zero-sized marker type, and the dispatch enums are generated by the
//! `block_authentication_schemes!` macro at the bottom of this file. Adding a
//! scheme therefore means: implement the trait for a marker (one macro line
//! for the crates already wired here) and add one line to that macro call.

use std::{fmt, marker::PhantomData, str::FromStr};

use serde::{Deserialize, Deserializer, Serialize, Serializer, de};

use crate::crypto::{AsBytes, BlockDigest, PublicKey, SignatureBytes, Signer};

// ---------------------------------------------------------------------------
// Generic post-quantum scheme abstraction
// ---------------------------------------------------------------------------

/// A digital-signature scheme usable for block authentication.
///
/// Implementors are zero-sized marker types. Messages are always the 32-byte
/// block content digest. All encodings are the scheme's standard byte
/// encodings (FIPS 204 / FIPS 205).
pub trait PqSignatureScheme:
    Clone + Copy + fmt::Debug + PartialEq + Eq + Send + Sync + 'static
{
    /// Stable, lower-case, kebab-case identifier (CLI / YAML value).
    const NAME: &'static str;
    const PUBLIC_KEY_SIZE: usize;
    /// Size of the serialized private key material.
    const SECRET_KEY_SIZE: usize;
    const SIGNATURE_SIZE: usize;

    type SigningKey: Clone + Send + Sync;
    type VerifyingKey: Clone + Send + Sync;

    /// Deterministically derive a signing key from 32 bytes of seed material.
    fn keygen_from_seed(seed: &[u8; 32]) -> Self::SigningKey;
    fn signing_key_to_bytes(key: &Self::SigningKey) -> Vec<u8>;
    fn signing_key_from_bytes(bytes: &[u8]) -> Option<Self::SigningKey>;
    fn verifying_key(key: &Self::SigningKey) -> Self::VerifyingKey;
    fn verifying_key_to_bytes(key: &Self::VerifyingKey) -> Vec<u8>;
    fn verifying_key_from_bytes(bytes: &[u8]) -> Option<Self::VerifyingKey>;
    fn sign(key: &Self::SigningKey, message: &[u8]) -> Vec<u8>;
    fn verify(key: &Self::VerifyingKey, message: &[u8], signature: &[u8]) -> bool;
}

/// Private signing key of scheme `S`. Boxed so moving the wrapper does not
/// copy secret material around the stack.
pub struct PqSigner<S: PqSignatureScheme>(Box<S::SigningKey>);

/// Public verifying key of scheme `S`, kept in decoded form so the hot
/// verification path does not re-parse it.
pub struct PqPublicKey<S: PqSignatureScheme>(S::VerifyingKey);

/// Encoded signature of scheme `S`. Length is validated on construction; the
/// scheme parses it again during verification.
pub struct PqSignature<S: PqSignatureScheme>(Box<[u8]>, PhantomData<S>);

impl<S: PqSignatureScheme> PqSigner<S> {
    pub fn from_seed(seed: &[u8; 32]) -> Self {
        Self(Box::new(S::keygen_from_seed(seed)))
    }

    pub fn from_bytes(bytes: &[u8]) -> Result<Self, String> {
        if bytes.len() != S::SECRET_KEY_SIZE {
            return Err(format!(
                "invalid {} secret key length {} (expected {})",
                S::NAME,
                bytes.len(),
                S::SECRET_KEY_SIZE
            ));
        }
        S::signing_key_from_bytes(bytes)
            .map(|key| Self(Box::new(key)))
            .ok_or_else(|| format!("invalid {} secret key encoding", S::NAME))
    }

    pub fn to_bytes(&self) -> Vec<u8> {
        S::signing_key_to_bytes(&self.0)
    }

    pub fn public_key(&self) -> PqPublicKey<S> {
        PqPublicKey(S::verifying_key(&self.0))
    }

    pub fn sign(&self, message: &[u8; 32]) -> PqSignature<S> {
        let bytes = S::sign(&self.0, message);
        debug_assert_eq!(bytes.len(), S::SIGNATURE_SIZE);
        PqSignature(bytes.into_boxed_slice(), PhantomData)
    }
}

impl<S: PqSignatureScheme> PqPublicKey<S> {
    pub fn from_bytes(bytes: &[u8]) -> Result<Self, String> {
        if bytes.len() != S::PUBLIC_KEY_SIZE {
            return Err(format!(
                "invalid {} public key length {} (expected {})",
                S::NAME,
                bytes.len(),
                S::PUBLIC_KEY_SIZE
            ));
        }
        S::verifying_key_from_bytes(bytes)
            .map(Self)
            .ok_or_else(|| format!("invalid {} public key encoding", S::NAME))
    }

    pub fn to_bytes(&self) -> Vec<u8> {
        S::verifying_key_to_bytes(&self.0)
    }

    pub fn verify(&self, message: &[u8; 32], signature: &PqSignature<S>) -> bool {
        S::verify(&self.0, message, &signature.0)
    }
}

impl<S: PqSignatureScheme> PqSignature<S> {
    pub fn from_bytes(bytes: &[u8]) -> Result<Self, String> {
        if bytes.len() != S::SIGNATURE_SIZE {
            return Err(format!(
                "invalid {} signature length {} (expected {})",
                S::NAME,
                bytes.len(),
                S::SIGNATURE_SIZE
            ));
        }
        Ok(Self(bytes.into(), PhantomData))
    }

    pub fn as_bytes(&self) -> &[u8] {
        &self.0
    }
}

impl<S: PqSignatureScheme> Clone for PqSigner<S> {
    fn clone(&self) -> Self {
        Self(self.0.clone())
    }
}

impl<S: PqSignatureScheme> Clone for PqPublicKey<S> {
    fn clone(&self) -> Self {
        Self(self.0.clone())
    }
}

impl<S: PqSignatureScheme> Clone for PqSignature<S> {
    fn clone(&self) -> Self {
        Self(self.0.clone(), PhantomData)
    }
}

impl<S: PqSignatureScheme> PartialEq for PqPublicKey<S> {
    fn eq(&self, other: &Self) -> bool {
        self.to_bytes() == other.to_bytes()
    }
}
impl<S: PqSignatureScheme> Eq for PqPublicKey<S> {}

impl<S: PqSignatureScheme> PartialEq for PqSignature<S> {
    fn eq(&self, other: &Self) -> bool {
        self.0 == other.0
    }
}
impl<S: PqSignatureScheme> Eq for PqSignature<S> {}

impl<S: PqSignatureScheme> fmt::Debug for PqSigner<S> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}Signer(public_key={:?})", S::NAME, self.public_key())
    }
}

impl<S: PqSignatureScheme> fmt::Debug for PqPublicKey<S> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}Pk({})", S::NAME, hex::encode(&self.to_bytes()[..4]))
    }
}

impl<S: PqSignatureScheme> fmt::Debug for PqSignature<S> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}Sig({})", S::NAME, hex::encode(&self.0[..4]))
    }
}

impl<S: PqSignatureScheme> Serialize for PqSigner<S> {
    fn serialize<Ser: Serializer>(&self, serializer: Ser) -> Result<Ser::Ok, Ser::Error> {
        serialize_bytes(&self.to_bytes(), serializer)
    }
}

